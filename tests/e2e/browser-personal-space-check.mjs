// Run against an isolated reader with at least one parsed PDF of two or more pages.
// Model settings are intercepted; no real credentials or model service are used.
import assert from 'node:assert/strict';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROMIUM_PATH || undefined, args: ['--no-sandbox'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const url = process.env.READER_URL || 'http://127.0.0.1:4174';
const errors = [];
page.on('pageerror', (error) => errors.push(error.message));
let collectionId;
let paper;
try {
  const papers = await (await page.request.get(url + '/api/documents')).json();
  paper = papers.find((item) => item.page_count >= 2);
  assert.ok(paper, 'seed an isolated reader with a parsed PDF first');
  await page.goto(url);
  await page.waitForFunction((count) => +document.querySelector('#stat-documents').textContent === count, papers.length);
  assert.equal(await page.locator('#reader-workspace').isVisible(), false);
  await page.locator('[data-space-route="library"]').click();
  await page.locator('#library-search').fill(paper.filename);
  assert.equal(await page.locator('#library-documents .paper-card').count(), 1);
  await page.locator('#library-search').fill('no-such-paper-314159');
  assert.match(await page.locator('#library-documents').textContent(), /没有找到/);
  await page.locator('#library-search').fill('');
  await page.locator('#edit-current-collection').click();
  const categoryName = `测试分类-${Date.now()}`;
  await page.locator('#collection-name').fill(categoryName);
  await page.locator('#create-collection-form button').click();
  await page.locator(`#collection-manager input[aria-label="分类名称：${categoryName}"]`).waitFor();
  const collections = await (await page.request.get(url + '/api/collections')).json();
  collectionId = collections.find((item) => item.name === categoryName).id;
  const row = page.locator('.collection-edit').filter({ has: page.locator(`input[aria-label="分类名称：${categoryName}"]`) });
  await row.locator('input').fill(categoryName + '-改名');
  await row.locator('button[type="submit"]').click();
  await page.locator(`#collection-manager input[aria-label="分类名称：${categoryName}-改名"]`).waitFor();
  await page.locator('#close-collections').click();
  const card = page.locator(`#library-documents [data-document-id="${paper.id}"]`);
  await card.locator('select').selectOption(collectionId);
  await page.waitForFunction(({ id, collectionId }) => document.querySelector(`#library-documents [data-document-id="${id}"] select`)?.value === collectionId, { id: paper.id, collectionId });
  await page.locator('#library-category').selectOption(collectionId);
  await page.waitForFunction(() => document.querySelector('#library-results').textContent === '共 1 篇论文');
  await page.reload();
  await card.locator('.paper-title').waitFor();
  assert.equal(await card.locator('select').inputValue(), collectionId, 'classification survives refresh');
  await card.locator('.paper-title').click();
  await page.waitForFunction(() => !document.querySelector('#page-number').disabled);
  await page.locator('#page-number').fill('2');
  await page.locator('#page-number').press('Enter');
  await page.waitForResponse((response) => response.url().endsWith(`/api/documents/${paper.id}/reading`) && response.request().postDataJSON().page === 2 && response.ok());
  await page.reload();
  await page.waitForFunction(() => document.querySelector('#translation-list').dataset.page === '2');
  assert.ok(await page.locator('.translation-tools #translation-model').isVisible(), 'model picker is available while reading');
  await page.locator('.toolbar-link[href="#home"]').click();
  await page.locator('#continue-reading .paper-title').waitFor();
  await page.reload();
  await page.locator('.space-reader-link').click();
  await page.waitForFunction(() => document.querySelector('#translation-list').dataset.page === '2');
  await page.locator('.toolbar-link[href="#home"]').click();
  await page.locator('#continue-reading .paper-title').waitFor();
  assert.equal(await page.locator('#continue-reading .paper-card').getAttribute('data-document-id'), paper.id);
  assert.match(await page.locator('#continue-reading').textContent(), /读至第 2 页/);
  await page.locator('[data-space-route="recent"]').click();
  await page.locator('#library-documents .paper-card').first().waitFor();
  assert.equal(await page.locator('#library-documents .paper-card').first().getAttribute('data-document-id'), paper.id);
  await page.locator('[data-space-route="library"]').click();
  await page.locator('#edit-current-collection').click();
  await page.locator('.collection-edit').filter({ has: page.locator(`input[aria-label="分类名称：${categoryName}-改名"]`) }).locator('.collection-delete').click();
  await page.waitForFunction((id) => !document.querySelector(`#library-category option[value="${id}"]`), collectionId);
  collectionId = null;
  await page.locator('#close-collections').click();
  assert.equal(await card.locator('select').inputValue(), '', 'deleting a category moves papers to unfiled');
  assert.ok((await page.request.get(url + '/api/documents/' + paper.id + '/pdf')).ok());

  let settings = { base_url: '', model: '', models: [], has_api_key: false };
  await page.route('**/api/translation/settings', async (route) => {
    if (route.request().method() === 'PUT') {
      const { api_key, ...publicSettings } = route.request().postDataJSON();
      settings = { ...publicSettings, has_api_key: !!api_key || settings.has_api_key };
    }
    await route.fulfill({ json: settings });
  });
  await page.route('**/api/translation/models', (route) => route.fulfill({ json: { models: settings.model ? [settings.model, ...settings.models] : [], default_model: settings.model || null } }));
  await page.locator('[data-space-route="settings"]').click();
  await page.waitForFunction(() => !document.querySelector('#save-llm-settings').disabled);
  await page.locator('#llm-base-url').fill('https://models.example/v1');
  await page.locator('#llm-api-key').fill('test-only-key');
  await page.locator('#llm-default-model').fill('model-a');
  await page.locator('#llm-models').fill('model-b');
  await page.locator('#save-llm-settings').click();
  await page.waitForFunction(() => document.querySelector('#llm-settings-success').textContent.includes('已保存'));
  assert.equal(await page.locator('#llm-api-key').inputValue(), '');
  await page.locator('.space-reader-link').click();
  assert.equal(await page.locator('#translation-model').inputValue(), 'model-a', 'saving settings selects the default model');
  await page.locator('#translation-model').selectOption('model-b');
  await page.reload();
  await page.waitForFunction(() => document.querySelector('#translation-model').value === 'model-b');
  await page.locator('.toolbar-link[href="#home"]').click();
  await page.locator('[data-space-route="settings"]').click();
  await page.waitForFunction(() => !document.querySelector('#save-llm-settings').disabled);
  assert.equal(await page.locator('#llm-default-model').inputValue(), 'model-a');
  assert.match(await page.locator('#llm-api-key').getAttribute('placeholder'), /已保存/);
  await page.locator('[data-space-route="home"]').click();
  await page.screenshot({ path: '/tmp/paperduo-personal-home.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('[data-space-route="library"]').click();
  await page.locator('#library-category').selectOption('unfiled');
  await page.waitForFunction(() => document.querySelector('#space-title').textContent === '未分类');
  assert.ok(await page.locator('#edit-current-collection').isVisible(), 'category management available on mobile');
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'no mobile horizontal overflow');
  await page.screenshot({ path: '/tmp/paperduo-personal-mobile.png', fullPage: true });
  // Empty libraries and failed requests remain usable and explain their state.
  await page.route('**/api/documents', (route) => route.fulfill({ json: [] }));
  await page.route('**/api/collections', (route) => route.fulfill({ json: [] }));
  await page.reload();
  await page.locator('#library-documents .library-empty button').waitFor();
  await page.route('**/api/documents', (route) => route.fulfill({ status: 503, json: { detail: '知识库暂时不可用' } }));
  await page.reload();
  await page.waitForFunction(() => document.querySelector('#space-feedback').textContent.includes('知识库暂时不可用'));
  assert.deepEqual(errors, []);
  console.log('personal space: home, search, category CRUD, unfiled, reading order, page restore, model settings, mobile passed');
} finally {
  if (collectionId) await page.request.delete(`${url}/api/collections/${collectionId}`);
  if (paper) await page.request.put(`${url}/api/documents/${paper.id}/collection`, { data: { collection_id: paper.collection_id } });
  await browser.close();
}
